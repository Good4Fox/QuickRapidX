import { invoke } from '@tauri-apps/api/core';

/**
 * Склад значков.
 *
 * Один и тот же файл попадается в списке не по разу, а вытаскивание значка —
 * обращение к оболочке Windows. Держим готовые ссылки и обещания: без второго
 * десяток строк с одним путём отправил бы десяток одинаковых запросов, пока
 * первый ещё не вернулся.
 *
 * Ядро отдаёт готовую ссылку `data:image/png`, рисовать на холсте не нужно.
 *
 * Запросы идут очередью. Список найденного на машине — это несколько сотен
 * строк, и без очереди все они уходили в ядро разом: оболочка Windows отвечала
 * на каждый по-своему долго, ответы приходили пачкой, и окно на это время
 * переставало отзываться на нажатия.
 */
const ready = new Map<string, string>();
const pending = new Map<string, Promise<string>>();

/*
 * Неудачи помним недолго.
 *
 * Прежде пустая строка ложилась на склад наравне с настоящей ссылкой, а
 * попадание проверяется на «не undefined» — то есть один сорвавшийся запрос
 * лишал программу значка навсегда. Навсегда здесь не оборот речи: окно набора
 * за весь сеанс не перезагружается ни разу, оно только прячется и просыпается.
 */
const MISS_KEEP = 15_000;
const missed = new Map<string, number>();

/*
 * Предел склада.
 *
 * Единственное место в программе, которое росло без остановки: значки клались
 * сюда и не убирались никогда. Каждый — строка `data:image/png;base64,…` в
 * несколько килобайт, и один и тот же файл может лежать здесь до шести раз, по
 * разу на каждый запрашиваемый размер. На машине с четырьмя сотнями программ
 * это мегабайты строк в каждом окне, которое хоть раз показывало список.
 *
 * Шестьсот — с запасом: столько строк не помещается ни в один наш список
 * разом, то есть выталкивание начнётся не раньше, чем список пролистают
 * целиком, а прокрутка обратно попадёт в склад.
 */
const KEEP = 4000;

/**
 * Кладёт значок на склад, вытесняя самый давний.
 *
 * Порядок вставки у `Map` сохраняется, поэтому первый ключ и есть самый
 * давний — отдельного учёта не нужно.
 */
function store(key: string, url: string) {
	ready.set(key, url);

	while (ready.size > KEEP) {
		const oldest = ready.keys().next().value;

		if (oldest === undefined) break;

		ready.delete(oldest);
	}
}

/** Сколько значков тянем одновременно. */
const LIMIT = 6;

let running = 0;
const queue: (() => void)[] = [];

function slot(): Promise<void> {
	if (running < LIMIT) {
		running += 1;
		return Promise.resolve();
	}

	return new Promise((release) => queue.push(() => release()));
}

function free() {
	const next = queue.shift();

	// Ниже нуля счётчик уходить не должен: запрос, зависший с прошлого показа,
	// возвращает свой слот уже после того, как очередь подняли заново
	if (next) next();
	else running = Math.max(0, running - 1);
}

/**
 * Возвращает очередь запросов в исправное состояние.
 *
 * Окно набора не закрывается, а прячется и усыпляется — своего запуска заново
 * у него нет, и всё, что застряло в прошлый раз, застряло навсегда. Показ и
 * есть тот единственный миг, когда это можно снять. Готовые ссылки не трогаем:
 * они верны, и перепрашивать их значило бы снова идти в оболочку Windows.
 */
export function revive() {
	pending.clear();
	missed.clear();

	const waiting = queue.splice(0, queue.length);

	// Отпущенные занимают слоты сразу: каждый вернёт свой, когда закончит
	running = waiting.length;

	for (const release of waiting) release();
}

/**
 * Размеры, в которых значки и вытаскиваются.
 *
 * Просить у системы ровно столько, сколько нужно разметке, — плохая мысль на
 * мелких размерах: в файле лежат заготовки определённых размеров, и на
 * восемнадцати пикселях выходит либо каша, либо ничего. Берём ближайший
 * стандартный сверху, а уменьшает уже разметка — она это делает сглаженно.
 *
 * Побочная польза: запросов становится меньше. Плитка в 44 и плитка в 40
 * теперь спрашивают один и тот же значок и берут его со склада.
 */
const STEPS = [32, 48, 64, 96, 128, 256];

function step(size: number): number {
	return STEPS.find((value) => value >= size) ?? STEPS[STEPS.length - 1];
}

export async function iconFor(path: string, wanted = 56): Promise<string> {
	/*
	 * Просим значок в настоящих пикселях экрана, а не в пикселях разметки.
	 *
	 * При масштабе 150% плитка в 44 занимает 66 настоящих точек, и значок,
	 * вытащенный в 48, приходилось растягивать — отсюда мыло. Разметка потом
	 * ужмёт картинку обратно, а уменьшение куда безобиднее увеличения.
	 */
	const ratio = typeof window === 'undefined' ? 1 : window.devicePixelRatio || 1;
	const size = step(Math.round(wanted * ratio));

	// Размер входит в ключ: один и тот же файл может понадобиться и мелким,
	// и крупным, а хранить крупный и сжимать — терять чёткость
	const key = `${size}:${path}`;

	const cached = ready.get(key);

	if (cached !== undefined) {
		// Переставляем в конец: иначе вытеснялось бы то, чем как раз и
		// пользуются, — список прокручивают туда-сюда по одним и тем же строкам
		ready.delete(key);
		ready.set(key, cached);

		return cached;
	}

	const miss = missed.get(key);

	if (miss !== undefined) {
		if (Date.now() - miss < MISS_KEEP) return '';

		missed.delete(key);
	}

	const busy = pending.get(key);
	if (busy) return busy;

	const task = extract(path, size)
		.then((url) => {
			// Неудача идёт в свою карту, а не на склад: со склада её никто
			// никогда не убрал бы, и место значка осталось бы пустым до конца
			if (url) store(key, url);
			else missed.set(key, Date.now());

			return url;
		})
		// На любом исходе: прежде ключ убирался только из `.then`, и отказ
		// оставлял в карте мёртвое обещание для всех, кто спросит потом
		.finally(() => pending.delete(key));

	pending.set(key, task);
	return task;
}

/*
 * Ссылка на значок вместо самого значка.
 *
 * Ядро кладёт готовый PNG в общее хранилище — один файл на всё приложение — и
 * отдаёт ключ. Ссылку по ключу строим здесь; картинку по ней тянет уже движок.
 *
 * Прежде сюда приходила строка `data:image/png;base64,…` в несколько килобайт.
 * Она оседала в памяти окна, а окон три — и один и тот же значок лежал в
 * каждом отдельно. Теперь в памяти только ключ, а картинку движок держит у
 * себя и сам же выбрасывает, когда она перестаёт быть нужна.
 */
/** Сколько ждём ядро, прежде чем считать запрос потерянным. */
const WAIT = 10_000;

async function extract(path: string, size: number): Promise<string> {
	await slot();

	let timer: ReturnType<typeof setTimeout> | undefined;

	try {
		/*
		 * Ответ может не прийти вовсе.
		 *
		 * Окно набора усыпляют по любому поводу — Esc, уход фокуса, запуск
		 * программы, — и запрос застаёт это на полпути. Без срока слот из шести
		 * не вернулся бы никогда, а после шести таких очередь окна встала бы
		 * намертво: значков не стало бы вообще ни у кого.
		 */
		const key = await Promise.race([
			invoke<string>('icon_key', { path, size }),
			new Promise<string>((_, stop) => {
				timer = setTimeout(() => stop(new Error('значка не дождались')), WAIT);
			})
		]);

		return key ? `${SCHEME}${key}` : '';
	} catch {
		// Значка нет — не беда: место займёт буква названия
		return '';
	} finally {
		clearTimeout(timer);
		free();
	}
}

/*
 * Начало ссылки на наш протокол.
 *
 * На Windows свои протоколы движок подаёт как `http://<имя>.localhost/…`, на
 * прочих системах — как `<имя>://…`. Проверяем по самому окружению, а не по
 * строке пользовательского агента: она врёт чаще, чем хотелось бы.
 */
const SCHEME =
	typeof navigator !== 'undefined' && navigator.userAgent.includes('Windows')
		? 'http://qrxicon.localhost/'
		: 'qrxicon://localhost/';

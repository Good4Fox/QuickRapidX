<script lang="ts">
	/*
	 * Значок программы.
	 *
	 * Имена классов начинаются с `qrx_appico` и заняты только здесь. Проверено
	 * поиском по всему проекту, и не зря: `qrx_icon` носили плитки выбора значка
	 * приложения в настройках, а `qrx_tile` — карточки стартовой страницы.
	 * Первое совпадение съедало значок отступом в 12 пикселей, второе схлопывало
	 * карточки в квадраты 56×56.
	 *
	 * Плитка всегда одна и та же: тот же размер, тот же радиус, та же подложка.
	 * Меняется только содержимое — настоящий значок или монограмма. Иначе
	 * получалось два разных объекта в одном списке: у одних программ логотип
	 * во всю плитку, у других буква на пустом месте, и ряд рассыпался. Особенно
	 * в витрине, где значков нет почти ни у кого: winget их не отдаёт вовсе.
	 *
	 * Настоящий значок не растягивается на всю плитку, а сидит внутри с
	 * отступом — так его оптический вес совпадает с весом монограммы.
	 */
	import { iconFor } from '$lib/state/icons';

	type Props = {
		/** Путь к файлу, у которого берётся значок. Пусто — сразу монограмма. */
		path: string;
		/** Название: из него собирается монограмма. */
		fallback: string;
		size?: number;
		/**
		 * Спрашивать значок сразу, не дожидаясь появления в видимой области.
		 *
		 * Для маленьких списков — окна набора, полоски в карточке — ожидание
		 * только вредит: значков там горстка, зато окно к этому времени успевает
		 * поменять размер, и наблюдатель может не заметить, что плитка уже видна.
		 */
		eager?: boolean;
		/**
		 * В каком размере просить значок у ядра.
		 *
		 * Пусто — в том же, в каком рисуем. Нужен там, где плитка мельче
		 * общепринятой: размер входит и в ключ склада, и в ключ хранилища на
		 * диске. Свой размер — это своё, ни с кем не общее место, а значит
		 * всегда пустое: сколько бы раз значок ни вытаскивали в других окнах,
		 * этой плитке придётся идти в оболочку Windows самой.
		 */
		want?: number;
	};

	let { path, fallback, size = 56, eager = false, want }: Props = $props();

	let src = $state('');
	let tile = $state<HTMLElement | null>(null);

	/*
	 * Значок спрашивается, только когда плитка подходит к видимой области.
	 *
	 * Список найденного на машине — несколько сотен строк, и каждая просила
	 * свой значок сразу при построении. Оболочка Windows отвечала на каждый
	 * запрос по-своему долго, и всё это время окно не отзывалось на нажатия,
	 * хотя видно из списка десяток строк.
	 */
	$effect(() => {
		const file = path?.trim();
		const node = tile;

		src = '';

		if (!file || !node) return;

		let alive = true;

		if (eager) {
			iconFor(file, want ?? size).then((url) => {
				if (alive) src = url;
			});

			return () => {
				alive = false;
			};
		}

		const watcher = new IntersectionObserver(
			(entries) => {
				if (!entries.some((entry) => entry.isIntersecting)) return;

				// Значок нужен один раз: дальше он лежит на складе
				watcher.disconnect();

				iconFor(file, want ?? size).then((url) => {
					if (alive) src = url;
				});
			},
			// Запас, чтобы значок успевал появиться до того, как строка доедет
			{ rootMargin: '240px' }
		);

		watcher.observe(node);

		return () => {
			alive = false;
			watcher.disconnect();
		};
	});

	/**
	 * Монограмма: до двух букв из значащих слов.
	 *
	 * Одна буква слишком часто совпадает — в списке из четырёхсот программ
	 * десятки начинаются на одну и ту же. Две различают заметно лучше.
	 */
	const monogram = $derived.by(() => {
		const words = (fallback || '')
			.replace(/[^\p{L}\p{N}\s.-]/gu, ' ')
			.split(/[\s.-]+/)
			.filter((word) => word.length > 0);

		if (words.length === 0) return '?';
		if (words.length === 1) return words[0].slice(0, 2).toUpperCase();

		return (words[0][0] + words[1][0]).toUpperCase();
	});
</script>

<!-- Пометка «значка нет»: там, где плитка без подложки, буквам она всё же
     нужна — иначе две висящие в воздухе буквы читаются как пустое место -->
<span
	class="qrx_appico"
	class:qrx_appico_empty={!src}
	bind:this={tile}
	style="--icon-size: {size}px"
>
	{#if src}
		<!-- draggable=false обязателен. Иначе движок начинает свой перенос
		     картинки раньше, чем ядро успеет начать перенос файла, и на панель
		     задач уезжает не ярлык, а сам значок в виде картинки.

		     onerror тоже обязателен: ключ мог быть выдан, а картинка по нему не
		     прийти — хранилище отвечает 404 при промахе. Без этого на месте
		     значка оставалась битая картинка, то есть пустое место даже без
		     букв: подложка с монограммой включается по пустому `src` -->
		<img class="qrx_appico_img" {src} alt="" draggable="false" onerror={() => (src = '')} />
	{:else}
		<span class="qrx_appico_mono" aria-hidden="true">{monogram}</span>
	{/if}
</span>
